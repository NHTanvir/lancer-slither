//! Markdown report emitter (uses `tera` templates).
//!
//! `--markdown` produces the full report; `--checklist` produces the compact
//! checkbox list.

use std::path::Path;

use once_cell::sync::Lazy;
use tera::{Context, Tera};

use crate::finding::{Finding, Impact, OutputResults};

static REPORT_TEMPLATE: &str = r#"# lancer-slither report

Generated by lancer-slither v{{ version }}.

{% if findings | length == 0 -%}
_No findings._
{%- else -%}
## Summary

| Impact | Count |
|---|---|
| High | {{ counts.high }} |
| Medium | {{ counts.medium }} |
| Low | {{ counts.low }} |
| Informational | {{ counts.informational }} |
| Optimization | {{ counts.optimization }} |

{% for tier in tiers -%}
{% if tier.count > 0 -%}
## {{ tier.name }}

{% for f in tier.findings -%}
### [{{ f.check }}] {{ f.title }}

**Confidence:** {{ f.confidence }}

{{ f.description }}

{% for el in f.elements -%}
- {{ el }}
{% endfor %}
{% endfor -%}
{% endif -%}
{% endfor -%}
{%- endif -%}
"#;

static CHECKLIST_TEMPLATE: &str = r#"# Slither checklist

{% if findings | length == 0 -%}
_No findings._
{%- else -%}
{% for tier in tiers -%}
{% if tier.count > 0 -%}
## {{ tier.name }}

{% for f in tier.findings -%}
- [ ] **{{ f.check }}** — {{ f.title }}
{% endfor %}
{% endif -%}
{% endfor -%}
{%- endif -%}
"#;

static TERA: Lazy<Tera> = Lazy::new(|| {
    let mut t = Tera::default();
    let _ = t.add_raw_template("report.md", REPORT_TEMPLATE);
    let _ = t.add_raw_template("checklist.md", CHECKLIST_TEMPLATE);
    t
});

pub fn write(path: &Path, results: &OutputResults, root_url: Option<&str>) -> eyre::Result<()> {
    let body = render(&results.results.detectors, root_url);
    std::fs::write(path, body)?;
    Ok(())
}

pub fn write_checklist(path: &Path, results: &OutputResults) -> eyre::Result<()> {
    let body = render_checklist(&results.results.detectors);
    std::fs::write(path, body)?;
    Ok(())
}

pub fn render(findings: &[Finding], root_url: Option<&str>) -> String {
    let ctx = build_context(findings, root_url);
    TERA.render("report.md", &ctx).unwrap_or_else(|e| {
        // tera should never fail on our static templates; fall back to a
        // minimal plain renderer if it somehow does.
        let _ = e;
        fallback_report(findings, root_url)
    })
}

pub fn render_checklist(findings: &[Finding]) -> String {
    let ctx = build_context(findings, None);
    TERA.render("checklist.md", &ctx).unwrap_or_else(|_| fallback_checklist(findings))
}

fn build_context(findings: &[Finding], root_url: Option<&str>) -> Context {
    let mut counts = serde_json::Map::new();
    for (k, imp) in [
        ("high", Impact::High),
        ("medium", Impact::Medium),
        ("low", Impact::Low),
        ("informational", Impact::Informational),
        ("optimization", Impact::Optimization),
    ] {
        counts.insert(
            k.to_owned(),
            serde_json::Value::Number(serde_json::Number::from(
                findings.iter().filter(|f| f.impact == imp).count(),
            )),
        );
    }
    let tiers: Vec<serde_json::Value> = [
        Impact::High,
        Impact::Medium,
        Impact::Low,
        Impact::Informational,
        Impact::Optimization,
    ]
    .iter()
    .map(|imp| {
        let bucket: Vec<_> = findings.iter().filter(|f| f.impact == *imp).collect();
        let entries: Vec<serde_json::Value> = bucket
            .iter()
            .map(|f| serde_json::json!({
                "check": f.check,
                "title": f.first_markdown_element,
                "confidence": f.confidence.to_string(),
                "description": f.description,
                "elements": f.elements.iter().map(|e| {
                    let pretty = e.source_mapping.pretty();
                    match root_url {
                        Some(r) => format!("{}/{}", r.trim_end_matches('/'), pretty),
                        None => pretty,
                    }
                }).collect::<Vec<_>>(),
            }))
            .collect();
        serde_json::json!({
            "name": imp.to_string(),
            "count": bucket.len(),
            "findings": entries,
        })
    })
    .collect();

    let mut ctx = Context::new();
    ctx.insert("version", env!("CARGO_PKG_VERSION"));
    ctx.insert("counts", &counts);
    ctx.insert("tiers", &tiers);
    ctx.insert("findings", findings);
    ctx
}

fn fallback_report(findings: &[Finding], _root_url: Option<&str>) -> String {
    use std::fmt::Write;
    let mut out = String::new();
    let _ = writeln!(out, "# lancer-slither report (fallback)\n");
    for f in findings {
        let _ = writeln!(out, "- [{}] {} — {}", f.impact, f.check, f.first_markdown_element);
    }
    out
}

fn fallback_checklist(findings: &[Finding]) -> String {
    use std::fmt::Write;
    let mut out = String::new();
    let _ = writeln!(out, "# Slither checklist (fallback)\n");
    for f in findings {
        let _ = writeln!(out, "- [ ] **{}** — {}", f.check, f.first_markdown_element);
    }
    out
}
